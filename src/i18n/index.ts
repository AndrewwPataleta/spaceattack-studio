export type Dict = typeof RU;
export type Key = keyof Dict;

// ── locale registry — populated by locales/<lang>.ts via register() (en is complete, rest partial) ───────────────
const REG: Partial<Record<Lang, Partial<Dict>>> = {};
export function register(l: Lang, dict: Partial<Dict>) { REG[l] = dict; }

// ── language resolution + active state ───────────────────────────────────────────────────────────────────────────
export function normalizeLang(raw?: string | null): Lang | null {
  if (!raw) return null;
  const s = raw.toLowerCase();
  const exact = SUPPORTED_LANGS.find((l) => l.toLowerCase() === s);
  if (exact) return exact;
  if (s.startsWith("zh")) return s.includes("hant") || s.includes("tw") || s.includes("hk") ? "zh-Hant" : "zh-Hans";
  if (s.startsWith("pt")) return "pt-BR";
  const base = SUPPORTED_LANGS.find((l) => l.split("-")[0] === s.split("-")[0]);
  return base ?? null;
}

// Resolution order: ①?lang= query (from webapp iframe) → ②saved (localStorage.arena_lang) → ③device (navigator) → ④en
let lang: Lang = ((): Lang => {
  if (typeof window === "undefined") return "en";
  const q = normalizeLang(new URLSearchParams(window.location.search).get("lang"));
  if (q) return q;
  const saved = normalizeLang(localStorage.getItem("arena_lang"));
  if (saved) return saved;
  const dev = normalizeLang(navigator.language);
  return dev ?? "en";
})();

const listeners = new Set<(l: Lang) => void>();
export function getLang() { return lang; }
export function setLang(l: Lang) { lang = l; try { localStorage.setItem("arena_lang", l); } catch { /* ignore */ } listeners.forEach((fn) => fn(l)); }

// ── resolver: overlay(active) → overlay(en) → ru base. A missing key degrades to English, then to the ru base. ────
function get(key: Key): Dict[Key] {
  const active = REG[lang]?.[key];
  if (active !== undefined) return active as Dict[Key];
  const en = REG["en"]?.[key];
  if (en !== undefined && lang !== "ru") return en as Dict[Key];
  return RU[key];
}

// t: string keys return the string; function keys are called with the passed args. Always returns a string.
export function t(key: Key, ...args: any[]): string {
  const v = get(key);
  return typeof v === "function" ? (v as (...a: any[]) => string)(...args) : (v as string);
}

// useT: light hook for the few screens with a live language switcher (re-renders on setLang).
export function useT() {
  const [l, setL] = useState<Lang>(lang);
  useEffect(() => { const fn = (nl: Lang) => setL(nl); listeners.add(fn); return () => { listeners.delete(fn); }; }, []);
  return { t, lang: l, setLang };
}
